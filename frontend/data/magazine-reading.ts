export function pinArticleHtml(pin: MagazinePin) {
  const more = MORE[pin.slug];
  if (!more) return pin.body;
  return `${pin.body}<h2>${more.h2}</h2>${more.p.map((paragraph) => `<p>${paragraph}</p>`).join("")}`;
}
