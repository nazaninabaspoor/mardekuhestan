function sectionsToHtml(sections: Section[]) {
  return sections
    .map(
      (section, index) =>
        `<h2 id="s-${index + 1}">${section.h2}</h2>${section.p.map((paragraph) => `<p>${paragraph}</p>`).join("")}`,
    )
    .join("");
}

export function pinArticleHtml(pin: MagazinePin) {
  const extra = MORE[pin.slug];
  if (!extra) return pin.body;
  const quote = extra.quote ? `<blockquote>${extra.quote}</blockquote>` : "";
  return `${pin.body}${quote}${sectionsToHtml(extra.sections)}`;
}

export function pinArticleFaqs(pin: MagazinePin) {
  return MORE[pin.slug]?.faqs ?? [];
}
