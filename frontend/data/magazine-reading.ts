export function pinArticleHeadline(pin: MagazinePin) {
  if (pin.slug === RAH_SABZ.slug) return RAH_SABZ.headline;
  return GUIDES[pin.slug]?.headline || pin.title;
}

export function pinArticleHtml(pin: MagazinePin) {
  if (pin.slug === RAH_SABZ.slug) return RAH_SABZ.body;
  const guide = GUIDES[pin.slug];
  if (!guide) return pin.body;
  const sections = guide.sections
    .map((section, index) => {
      const listHtml = section.list?.length ? list(section.list) : "";
      return `${heading(`s-${index + 1}`, section.h2)}${paras(section.p)}${listHtml}`;
    })
    .join("");
  return `${paras(guide.intro)}${sections}${heading("s-close", "سخن آخر")}${paras(guide.close)}`;
}

export function pinArticleFaqs(pin: MagazinePin) {
  if (pin.slug === RAH_SABZ.slug) return RAH_SABZ.faqs;
  return GUIDES[pin.slug]?.faqs ?? [];
}

export function pinArticlePack(pin: MagazinePin) {
  if (pin.slug !== RAH_SABZ.slug) return null;
  return RAH_SABZ;
}
